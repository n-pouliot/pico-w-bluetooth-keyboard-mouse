/**
 * @brief Start connecting after boot up: load bonded device if present, then always start scanning.
 */
static void hog_start_connect(void)
{
    // check if we have a bonded device
    btstack_tlv_get_instance(&btstack_tlv_singleton_impl, &btstack_tlv_singleton_context);
    if (btstack_tlv_singleton_impl){
        int len = btstack_tlv_singleton_impl->get_tag(btstack_tlv_singleton_context, TLV_TAG_HOGD, (uint8_t *) &bonded_device, sizeof(bonded_device));
        if (len == sizeof(bonded_device)){
            has_bonded_device = true;
            BLE_LOG("Bonded device loaded (%s, type %u). Starting scan...\n", 
                    bd_addr_to_str(bonded_device.addr), bonded_device.addr_type);
        } else {
            has_bonded_device = false;
        }
    } else {
        has_bonded_device = false;
    }
    // Always start scanning to reliably discover RPA or public advertising without blocking
    hog_start_scan();
}

/**
 * @brief Connect to target device with a connection timeout timer.
 */
static void hog_connect(void)
{
    BLE_LOG("Connecting to device %s (type %u, Timeout %dms)...\n", 
            bd_addr_to_str(target_device.addr), target_device.addr_type, CONNECTION_TIMEOUT_MS);
    
    // Fix: Remove timer before adding. If a previous timer (like scan timeout) is still active, 
    // btstack_run_loop_add_timer would trigger an assertion failure.
    btstack_run_loop_remove_timer(&connection_timer);

    // Set timer for connection attempt
    btstack_run_loop_set_timer(&connection_timer, CONNECTION_TIMEOUT_MS);
    btstack_run_loop_set_timer_handler(&connection_timer, &hog_connection_timeout);
    btstack_run_loop_add_timer(&connection_timer);
    
    app_state = W4_CONNECTED;
    gap_connect(target_device.addr, target_device.addr_type);
}

/**
 * @brief Start scanning for LE HID devices.
 */
static void hog_start_scan(void)
{
    BLE_LOG("Scanning for LE HID devices (Timeout %dms)...\n", SCAN_TIMEOUT_MS);
    app_state = W4_HID_DEVICE_FOUND;

    // Fix: Remove timer before adding to prevent assertion if scan is restarted during reconnection
    btstack_run_loop_remove_timer(&connection_timer);

    // Set timer to refresh scanning
    btstack_run_loop_set_timer(&connection_timer, SCAN_TIMEOUT_MS);
    btstack_run_loop_set_timer_handler(&connection_timer, &hog_scan_timeout);
    btstack_run_loop_add_timer(&connection_timer);

    // Passive scanning, 100% (scan interval = scan window)
    gap_set_scan_parameters(0,48,48);
    gap_start_scan();
}

/**
 * @brief Handle scan timeout by restarting scan.
 * @param ts Pointer to timer source structure.
 */
static void hog_scan_timeout(btstack_timer_source_t * ts)
{
    UNUSED(ts);
    if (app_state != W4_HID_DEVICE_FOUND) return;
    BLE_LOG("Scan timeout. Refreshing scan...\n");
    hog_start_scan();
}

/**
 * @brief Handle connection timeout by cancelling connection attempt and restarting scan.
 * @param ts Pointer to timer source structure.
 */
static void hog_connection_timeout(btstack_timer_source_t * ts)
{
    UNUSED(ts);
    BLE_LOG("Connection timeout. Switching to scan...\n");
    gap_connect_cancel();
    hog_start_scan();
}

/**
 * @brief Handle reconnection delay timer callback after disconnection.
 * @param ts Pointer to timer source structure.
 */
static void hog_reconnect_timeout(btstack_timer_source_t * ts)
{
    UNUSED(ts);
    hog_start_connect();
}

/**
 * @brief Handle connection error by disconnecting and restarting scan.
 */
static void handle_outgoing_connection_error(void)
{
    BLE_LOG("Error occurred, disconnect and start over\n");
    if (connection_handle != HCI_CON_HANDLE_INVALID) {
        gap_disconnect(connection_handle);
        // Do not call hog_start_scan() synchronously here; HCI_EVENT_DISCONNECTION_COMPLETE
        // will handle timer clearing and clean restart after controller disconnection.
    } else {
        hog_start_scan();
    }
}

/**
 * @brief Request optimized connection parameters for HID device.
 */
static void request_hid_connection_parameters(void)
{
    if (connection_handle == HCI_CON_HANDLE_INVALID) return;
    gap_request_connection_parameter_update(connection_handle,
                                             CONN_INTERVAL_MIN_UNITS,
                                             CONN_INTERVAL_MAX_UNITS,
                                             CONN_LATENCY_EVENTS,
                                             CONN_TIMEOUT_UNITS);
}

/**
 * @brief Check if advertising address is a Resolvable Private Address (RPA).
 * @param addr_type Address type.
 * @param addr Bluetooth address.
 * @return true if address is an RPA, false otherwise.
 */
static bool is_resolvable_private_address(bd_addr_type_t addr_type, const bd_addr_t addr)
{
    // RPA is a Random Address where top two bits are 01b (0x40 - 0x7F)
    return (addr_type == BD_ADDR_TYPE_LE_RANDOM) && ((addr[0] & 0xC0) == 0x40);
}

/**
 * @brief Check if advertising event packet contains HID service UUID or HID Appearance.
 * @param packet Pointer to advertising report packet.
 * @return true if HID service UUID or HID Appearance is found, false otherwise.
 */
static bool adv_event_contains_hid_service(const uint8_t * packet)
{
    const uint8_t * ad_data = gap_event_advertising_report_get_data(packet);
    uint8_t ad_len = gap_event_advertising_report_get_data_length(packet);
    if (ad_data_contains_uuid16(ad_len, ad_data, ORG_BLUETOOTH_SERVICE_HUMAN_INTERFACE_DEVICE)) {
        return true;
    }
    // Check Appearance AD structure (AD Type 0x19) for HID Categories (0x03C0 - 0x03CF)
    for (int i = 0; i + 3 <= ad_len;) {
        uint8_t len = ad_data[i];
        if (len == 0) break;
        if (i + 1 + len > ad_len) break;
        uint8_t type = ad_data[i + 1];
        if (type == 0x19 && len >= 3) {
            uint16_t appearance = (uint16_t)ad_data[i + 2] | ((uint16_t)ad_data[i + 3] << 8);
            if (appearance >= 0x03C0 && appearance <= 0x03CF) {
                return true;
            }
        }
        i += 1 + len;
    }
    return false;
}

/**
 * @brief Check if an RPA address resolution is already in progress.
 * @param addr RPA address.
 * @return true if address is already tracked and pending, false otherwise.
 */
static bool is_rpa_lookup_pending(const bd_addr_t addr)
{
    for (int i = 0; i < MAX_PENDING_RPA_LOOKUPS; i++) {
        if (pending_rpa_lookups[i].in_use && memcmp(pending_rpa_lookups[i].addr, addr, 6) == 0) {
            return true;
        }
    }
    return false;
}

/**
 * @brief Clear all pending RPA lookup records (e.g. upon disconnection).
 */
static void clear_all_pending_rpa_lookups(void)
{
    for (int i = 0; i < MAX_PENDING_RPA_LOOKUPS; i++) {
        pending_rpa_lookups[i].in_use = false;
    }
}

/**
 * @brief Clear a specific pending RPA lookup record upon resolution success.
 * @param addr RPA address.
 */
static void clear_pending_rpa_lookup(const bd_addr_t addr)
{
    for (int i = 0; i < MAX_PENDING_RPA_LOOKUPS; i++) {
        if (pending_rpa_lookups[i].in_use && memcmp(pending_rpa_lookups[i].addr, addr, 6) == 0) {
            pending_rpa_lookups[i].in_use = false;
        }
    }
}

/**
 * @brief Track an outgoing RPA address resolution request with its advertisement HID presence.
 * @param addr RPA address.
 * @param has_hid_service true if advertisement payload contained HID service UUID.
 */
static void track_pending_rpa_lookup(const bd_addr_t addr, bool has_hid_service)
{
    // If already exists in table, update the entry in place
    for (int i = 0; i < MAX_PENDING_RPA_LOOKUPS; i++) {
        if (pending_rpa_lookups[i].in_use && memcmp(pending_rpa_lookups[i].addr, addr, 6) == 0) {
            pending_rpa_lookups[i].has_hid_service = has_hid_service;
            return;
        }
    }

    memcpy(pending_rpa_lookups[pending_rpa_lookup_index].addr, addr, 6);
    pending_rpa_lookups[pending_rpa_lookup_index].has_hid_service = has_hid_service;
    pending_rpa_lookups[pending_rpa_lookup_index].in_use = true;
    pending_rpa_lookup_index = (pending_rpa_lookup_index + 1) % MAX_PENDING_RPA_LOOKUPS;
}

/**
 * @brief Retrieve and consume the HID advertisement status for an unresolved RPA.
 * @param addr RPA address.
 * @return true if advertisement contained HID service UUID, false otherwise.
 */
static bool get_and_clear_pending_rpa_has_hid_service(const bd_addr_t addr)
{
    for (int i = 0; i < MAX_PENDING_RPA_LOOKUPS; i++) {
        if (pending_rpa_lookups[i].in_use && memcmp(pending_rpa_lookups[i].addr, addr, 6) == 0) {
            pending_rpa_lookups[i].in_use = false;
            return pending_rpa_lookups[i].has_hid_service;
        }
    }
    return false;
}

