/**
 * @brief Periodic timer callback executed on Core 1 (BTstack run loop) to drive the status LED.
 * @param ts Pointer to timer source structure.
 */
static void led_timer_handler(btstack_timer_source_t * ts)
{
    static bool led_state = false;

    if (app_state == READY) {
        // Turn on LED continuously when in READY state
        if (!led_state) {
            cyw43_arch_gpio_put(CYW43_WL_GPIO_LED_PIN, true);
            led_state = true;
        }
    } else {
        // Blink LED every 200ms when not connected / connecting
        led_state = !led_state;
        cyw43_arch_gpio_put(CYW43_WL_GPIO_LED_PIN, led_state);
    }

    // Re-arm the timer
    btstack_run_loop_set_timer(ts, LED_BLINKING_INTERVAL_MS);
    btstack_run_loop_add_timer(ts);
}

