/**
 * @brief HCI and GAP event packet handler.
 * @param packet_type Type of incoming packet.
 * @param channel Channel ID.
 * @param packet Pointer to packet payload.
 * @param size Size of packet.
 */
static void packet_handler(uint8_t packet_type, uint16_t channel, uint8_t *packet, uint16_t size)
{
    UNUSED(channel);
    UNUSED(size);
    uint8_t event;

    switch (packet_type) {
        case HCI_EVENT_PACKET:
            event = hci_event_packet_get_type(packet);
            switch (event) {
                case BTSTACK_EVENT_STATE:
                    if (btstack_event_state_get_state(packet) != HCI_STATE_WORKING) break;
                    btstack_assert(app_state == W4_WORKING);
                    
                    hog_start_connect();
                    break;
                case GAP_EVENT_ADVERTISING_REPORT:
                {
                    if (app_state != W4_HID_DEVICE_FOUND) break;
                    
                    bd_addr_t adv_addr;
                    gap_event_advertising_report_get_address(packet, adv_addr);
                    bd_addr_type_t raw_addr_type = gap_event_advertising_report_get_address_type(packet);
                    // Normalize address type (0=Public, 1=Random, 2=Public Identity -> 0, 3=Random Identity -> 1)
                    bd_addr_type_t adv_addr_type = (bd_addr_type_t)(raw_addr_type & 1);
                    bool has_hid_service = adv_event_contains_hid_service(packet);
                    
                    // 1. If bonded device exists and incoming address is an RPA, resolve address against IRK in le_device_db
                    // Skip duplicated lookups if address is already being resolved
                    if (has_bonded_device && is_resolvable_private_address(adv_addr_type, adv_addr)) {
                        if (!is_rpa_lookup_pending(adv_addr)) {
                            track_pending_rpa_lookup(adv_addr, has_hid_service);
                            sm_address_resolution_lookup(adv_addr_type, adv_addr);
                        }
                        break;
                    }

                    // 2. Direct match with bonded identity address (Public / Static Random address)
                    if (has_bonded_device && (memcmp(adv_addr, bonded_device.addr, 6) == 0)) {
                        BLE_LOG("Found bonded device %s directly, connecting...\n", bd_addr_to_str(adv_addr));
                        btstack_run_loop_remove_timer(&connection_timer);
                        gap_stop_scan();

                        memcpy(target_device.addr, adv_addr, 6);
                        target_device.addr_type = adv_addr_type;
                        hog_connect();
                        break;
                    }

                    // 3. New HID Device Advertisement (Device in pairing mode or active HID advertising)
                    if (has_hid_service) {
                        BLE_LOG("Found HID device %s (type %u), connecting...\n", bd_addr_to_str(adv_addr), adv_addr_type);
                        btstack_run_loop_remove_timer(&connection_timer);
                        gap_stop_scan();

                        memcpy(target_device.addr, adv_addr, 6);
                        target_device.addr_type = adv_addr_type;
                        hog_connect();
                        break;
                    }
                    break;
                }
                case HCI_EVENT_DISCONNECTION_COMPLETE:
                {
                    uint8_t reason = hci_event_disconnection_complete_get_reason(packet);
                    const char * reason_str = "Unknown";
                    switch (reason) {
                        case ERROR_CODE_CONNECTION_TIMEOUT:
                            reason_str = "Connection Timeout (0x08)";
                            break;
                        case ERROR_CODE_REMOTE_USER_TERMINATED_CONNECTION:
                            reason_str = "Remote User Terminated / Keyboard disconnected (0x13)";
                            break;
                        case ERROR_CODE_REMOTE_DEVICE_TERMINATED_CONNECTION_DUE_TO_LOW_RESOURCES:
                            reason_str = "Remote Device Low Resources (0x14)";
                            break;
                        case ERROR_CODE_REMOTE_DEVICE_TERMINATED_CONNECTION_DUE_TO_POWER_OFF:
                            reason_str = "Remote Device Power Off (0x15)";
                            break;
                        case ERROR_CODE_CONNECTION_TERMINATED_BY_LOCAL_HOST:
                            reason_str = "Local Host Terminated (0x16)";
                            break;
                        case ERROR_CODE_LMP_RESPONSE_TIMEOUT_LL_RESPONSE_TIMEOUT:
                            reason_str = "LMP/LL Response Timeout (0x22)";
                            break;
                        case ERROR_CODE_UNACCEPTABLE_CONNECTION_PARAMETERS:
                            reason_str = "Unacceptable Connection Parameters (0x3B)";
                            break;
                        default:
                            break;
                    }
                    connection_handle = HCI_CON_HANDLE_INVALID;
                    BLE_LOG("Disconnected (Reason: 0x%02x - %s), restarting in %d ms...\n", reason, reason_str, RECONNECT_DELAY_MS);
                    
                    // Fix: Ensure timer and pending RPA lookups are cleared upon disconnection before starting over
                    btstack_run_loop_remove_timer(&connection_timer);
                    clear_all_pending_rpa_lookups();

                    // Wait a short delay before restarting the connection loop to allow both BLE controller and remote peripheral to stabilize
                    app_state = W4_WORKING;
                    btstack_run_loop_set_timer(&connection_timer, RECONNECT_DELAY_MS);
                    btstack_run_loop_set_timer_handler(&connection_timer, &hog_reconnect_timeout);
                    btstack_run_loop_add_timer(&connection_timer);
                    break;
                }
                case HCI_EVENT_META_GAP:
                    // wait for connection complete
                    if (hci_event_gap_meta_get_subevent_code(packet) != GAP_SUBEVENT_LE_CONNECTION_COMPLETE) break;
                    if (app_state != W4_CONNECTED) return;
                    btstack_run_loop_remove_timer(&connection_timer);
                    {
                        uint8_t status = gap_subevent_le_connection_complete_get_status(packet);
                        if (status != ERROR_CODE_SUCCESS) {
                            BLE_LOG("LE Connection failed (Status: 0x%02x). Restarting scan...\n", status);
                            connection_handle = HCI_CON_HANDLE_INVALID;
                            hog_start_scan();
                            break;
                        }
                    }
                    connection_handle = gap_subevent_le_connection_complete_get_connection_handle(packet);
                    // request security
                    app_state = W4_ENCRYPTED;
                    sm_request_pairing(connection_handle);
                    break;
                default:
                    break;
            }
            break;
        default:
            break;
    }
}

/**
 * @brief Security Manager (SM) packet handler for pairing, identity, and re-encryption events.
 * @param packet_type Type of incoming packet.
 * @param channel Channel ID.
 * @param packet Pointer to packet payload.
 * @param size Size of packet.
 */
static void sm_packet_handler(uint8_t packet_type, uint16_t channel, uint8_t *packet, uint16_t size)
{
    UNUSED(channel);
    UNUSED(size);

    if (packet_type != HCI_EVENT_PACKET) return;

    bool connect_to_service = false;

    switch (hci_event_packet_get_type(packet)) {
        case SM_EVENT_JUST_WORKS_REQUEST:
            BLE_LOG("Just works requested\n");
            sm_just_works_confirm(sm_event_just_works_request_get_handle(packet));
            break;
        case SM_EVENT_NUMERIC_COMPARISON_REQUEST:
            BLE_LOG("Confirming numeric comparison: %06"PRIu32"\n", sm_event_numeric_comparison_request_get_passkey(packet));
            sm_numeric_comparison_confirm(sm_event_numeric_comparison_request_get_handle(packet));
            break;
        case SM_EVENT_PASSKEY_DISPLAY_NUMBER:
            BLE_LOG("Display Passkey: %06"PRIu32"\n", sm_event_passkey_display_number_get_passkey(packet));
            break;
        case SM_EVENT_IDENTITY_RESOLVING_SUCCEEDED:
        {
            bd_addr_t resolved_identity_addr;
            bd_addr_t rpa_addr;
            sm_event_identity_resolving_succeeded_get_identity_address(packet, resolved_identity_addr);
            bd_addr_type_t resolved_identity_type = sm_event_identity_resolving_succeeded_get_identity_addr_type(packet);
            sm_event_identity_resolving_succeeded_get_address(packet, rpa_addr);
            bd_addr_type_t rpa_addr_type = (bd_addr_type_t)(sm_event_identity_resolving_succeeded_get_addr_type(packet) & 1);
            
            // Clear pending tracking entry for this RPA
            clear_pending_rpa_lookup(rpa_addr);

            BLE_LOG("SM: RPA %s resolved to Identity %s (type %u)\n", 
                    bd_addr_to_str(rpa_addr), bd_addr_to_str(resolved_identity_addr), resolved_identity_type);
            
            if (has_bonded_device && (memcmp(resolved_identity_addr, bonded_device.addr, 6) == 0)) {
                if (app_state == W4_HID_DEVICE_FOUND) {
                    BLE_LOG("Resolved RPA matches bonded peripheral! Connecting to RPA %s...\n", bd_addr_to_str(rpa_addr));
                    btstack_run_loop_remove_timer(&connection_timer);
                    gap_stop_scan();
                    memcpy(target_device.addr, rpa_addr, 6);
                    target_device.addr_type = rpa_addr_type;
                    hog_connect();
                }
            }
            break;
        }
        case SM_EVENT_IDENTITY_RESOLVING_FAILED:
        {
            bd_addr_t rpa_addr;
            sm_event_identity_resolving_failed_get_address(packet, rpa_addr);
            bd_addr_type_t rpa_addr_type = (bd_addr_type_t)(sm_event_identity_resolving_failed_get_addr_type(packet) & 1);
            bool adv_had_hid = get_and_clear_pending_rpa_has_hid_service(rpa_addr);

            // If the unresolved RPA explicitly contains the HID service UUID or HID Appearance,
            // connect as new device or re-pairing device.
            if (adv_had_hid && (app_state == W4_HID_DEVICE_FOUND)) {
                BLE_LOG("SM: Unresolved RPA %s has HID service, connecting as new device...\n", bd_addr_to_str(rpa_addr));
                btstack_run_loop_remove_timer(&connection_timer);
                gap_stop_scan();
                memcpy(target_device.addr, rpa_addr, 6);
                target_device.addr_type = rpa_addr_type;
                hog_connect();
            } else {
                // BLE_LOG("SM: RPA %s not resolved & no HID service (ignored)\n", bd_addr_to_str(rpa_addr));
            }
            break;
        }
        case SM_EVENT_IDENTITY_CREATED:
        {
            bd_addr_t identity_addr;
            sm_event_identity_created_get_identity_address(packet, identity_addr);
            bd_addr_type_t identity_addr_type = sm_event_identity_created_get_identity_addr_type(packet);
            BLE_LOG("SM: Identity created: %s (type %u)\n", bd_addr_to_str(identity_addr), identity_addr_type);
            memcpy(bonded_device.addr, identity_addr, 6);
            bonded_device.addr_type = identity_addr_type;
            has_bonded_device = true;
            break;
        }
        case SM_EVENT_PAIRING_COMPLETE:
            switch (sm_event_pairing_complete_get_status(packet)){
                case ERROR_CODE_SUCCESS:
                    BLE_LOG("Pairing complete, success\n");
                    request_hid_connection_parameters();
                    connect_to_service = true;
                    break;
                case ERROR_CODE_CONNECTION_TIMEOUT:
                    BLE_LOG("Pairing failed, timeout\n");
                    handle_outgoing_connection_error();
                    break;
                case ERROR_CODE_PIN_OR_KEY_MISSING:
                case ERROR_CODE_AUTHENTICATION_FAILURE:
                    BLE_LOG("Pairing failed (Key missing/Auth failure: 0x%02x). Clearing bond & restarting...\n", 
                            sm_event_pairing_complete_get_status(packet));
                    btstack_tlv_get_instance(&btstack_tlv_singleton_impl, &btstack_tlv_singleton_context);
                    if (btstack_tlv_singleton_impl) {
                        btstack_tlv_singleton_impl->delete_tag(btstack_tlv_singleton_context, TLV_TAG_HOGD);
                    }
                    gap_delete_bonding(target_device.addr_type, target_device.addr);
                    if (has_bonded_device) {
                        gap_delete_bonding(bonded_device.addr_type, bonded_device.addr);
                    }
                    has_bonded_device = false;
                    handle_outgoing_connection_error();
                    break;
                default:
                    BLE_LOG("Pairing failed, status 0x%02x\n", sm_event_pairing_complete_get_status(packet));
                    handle_outgoing_connection_error();
                    break;
            }
            break;
        case SM_EVENT_REENCRYPTION_COMPLETE:
            BLE_LOG("Re-encryption complete, success\n");
            request_hid_connection_parameters();
            connect_to_service = true;
            break;
        default:
            break;
    }

    if (connect_to_service){
        // continue - query primary services
        BLE_LOG("Search for HID service.\n");
        app_state = W4_HID_CLIENT_CONNECTED;
        hids_client_connect(connection_handle, handle_gatt_client_event, protocol_mode, &hids_cid);
    }
}

/**
 * @brief Handle GATT Client events dependent on current application state.
 * @param packet_type Type of incoming packet.
 * @param channel Channel ID.
 * @param packet Pointer to packet payload.
 * @param size Size of packet.
 */
static void handle_gatt_client_event(uint8_t packet_type, uint16_t channel, uint8_t *packet, uint16_t size)
{
    UNUSED(packet_type);
    UNUSED(channel);
    UNUSED(size);

    uint8_t status;

    if (hci_event_packet_get_type(packet) != HCI_EVENT_GATTSERVICE_META){
        return;
    }
    
    switch (hci_event_gattservice_meta_get_subevent_code(packet)){
        case GATTSERVICE_SUBEVENT_HID_SERVICE_CONNECTED:
            status = gattservice_subevent_hid_service_connected_get_status(packet);
            switch (status){
                case ERROR_CODE_SUCCESS:
                    BLE_LOG("HID service client connected, found %d services\n", 
                        gattservice_subevent_hid_service_connected_get_num_instances(packet));
        
                    if (!has_bonded_device || (!is_resolvable_private_address(target_device.addr_type, target_device.addr) && memcmp(bonded_device.addr, target_device.addr, 6) != 0)) {
                        if (!is_resolvable_private_address(target_device.addr_type, target_device.addr)) {
                            memcpy(&bonded_device, &target_device, sizeof(bonded_device));
                            bonded_device.addr_type = (bd_addr_type_t)(bonded_device.addr_type & 1);
                        }
                        has_bonded_device = true;
                    }

                    // store bonded identity address in TLV
                    btstack_tlv_get_instance(&btstack_tlv_singleton_impl, &btstack_tlv_singleton_context);
                    if (btstack_tlv_singleton_impl){
                        btstack_tlv_singleton_impl->store_tag(btstack_tlv_singleton_context, TLV_TAG_HOGD, (const uint8_t *) &bonded_device, sizeof(bonded_device));
                        BLE_LOG("Stored bonded identity %s (type %u) in TLV\n", bd_addr_to_str(bonded_device.addr), bonded_device.addr_type);
                    }
                    // done
                    BLE_LOG("Ready - please start typing or mousing..\n");
                    if (app_state != READY) {
                        app_state = READY;
                        // Re-initialize the USB device to make the USB host re-acquire the descriptor.
                        // This flag is referenced by USB task.
                        g_usb_reinit_request = true;
                    }
                    break;
                default:
                    BLE_LOG("HID service client connection failed, status 0x%02x.\n", status);
                    handle_outgoing_connection_error();
                    break;
            }
            break;

        case GATTSERVICE_SUBEVENT_HID_SERVICE_DISCONNECTED:
            BLE_LOG("HID service client disconnected\n");
            break;

        case GATTSERVICE_SUBEVENT_HID_REPORT:
            hid_handle_input_report(
                gattservice_subevent_hid_report_get_service_index(packet),
                gattservice_subevent_hid_report_get_report_id(packet), 
                gattservice_subevent_hid_report_get_report(packet), 
                gattservice_subevent_hid_report_get_report_len(packet));
            break;

        default:
            break;
    }
}

